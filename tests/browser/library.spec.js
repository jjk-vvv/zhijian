import { test, expect } from '@playwright/test'

test('发现页：分类、搜索、排序、详情与弹窗键盘操作', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.book-card')).toHaveCount(8)
  await expect(page.locator('.hero-photo')).toBeVisible()
  await page.getByRole('button', { name: '自然行旅', exact: true }).click()
  await expect(page.locator('.book-card')).toHaveCount(2)
  await page.getByRole('searchbox', { name: '搜索书名或作者' }).fill('不存在的书')
  await expect(page.getByRole('heading', { name: '还没找到这本书' })).toBeVisible()
  await page.getByRole('button', { name: '查看全部书籍' }).click()
  await page.getByLabel('书籍排序').selectOption('year')
  await expect(page.locator('.book-card').first()).toContainText('小王子')
  await page.getByRole('button', { name: '查看《瓦尔登湖》详情', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: '关闭弹窗' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('link', { name: '写手记', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(
    page.getByRole('button', { name: '查看《瓦尔登湖》详情', exact: true }),
  ).toBeFocused()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

test('书架：收藏、进度、状态切换、刷新保存与移出', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '收藏《月亮与六便士》' }).click()
  await expect(page.getByRole('button', { name: '《月亮与六便士》已在书架' })).toBeDisabled()
  await page.getByRole('link', { name: /^我的书架/ }).click()
  await expect(page.locator('.shelf-book')).toHaveCount(4)
  const card = page
    .locator('.shelf-book')
    .filter({ has: page.getByRole('heading', { name: '月亮与六便士', exact: true }) })
  await card.getByRole('slider').fill('65')
  await expect(card.locator('output')).toHaveText('65%')
  await page.reload()
  await expect(card.locator('output')).toHaveText('65%')
  await card.getByRole('button', { name: '标记读完' }).click()
  await page.getByRole('button', { name: /^已读完/ }).click()
  await expect(page.locator('.shelf-book')).toHaveCount(2)
  await card.getByRole('button', { name: '移出《月亮与六便士》' }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: '移出《月亮与六便士》' }).click()
  await page.getByRole('button', { name: '移出书架', exact: true }).click()
  await expect(page.locator('.shelf-book')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

test('手记：表单校验、实时预览、创建、编辑、搜索与删除', async ({ page }) => {
  await page.goto('/#/notes?compose=1&book=moon')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('手记标题')).toBeFocused()
  await expect(page.getByLabel('关于哪本书')).toHaveValue('moon')
  await page.getByRole('button', { name: '保存手记' }).click()
  await expect(page.getByText('给这篇手记起一个标题吧。')).toBeVisible()
  await page.getByLabel('手记标题').fill('午后的阅读')
  await page.getByLabel('正文').fill('从书里看见生活，也开始留意窗外的风景。')
  await expect(page.locator('.note-preview')).toContainText('午后的阅读')
  await page.getByRole('button', { name: '保存手记' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.note-card')).toHaveCount(2)
  await page.reload()
  await page.getByRole('button', { name: '编辑手记：午后的阅读' }).click()
  await page.getByLabel('手记标题').fill('更新后的阅读')
  await page.getByRole('button', { name: '保存手记' }).click()
  await page.getByRole('searchbox', { name: '搜索手记' }).fill('更新后')
  await expect(page.locator('.note-card')).toHaveCount(1)
  await page.getByRole('button', { name: '删除手记：更新后的阅读' }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '没有找到相关的手记' })).toBeVisible()
  await page.getByRole('button', { name: '查看全部手记' }).click()
  await expect(page.locator('.note-card')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

test('空记录、损坏存储与未知路由可恢复', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() =>
    localStorage.setItem('zhijian-library-v1', JSON.stringify({ shelf: [], notes: [] })),
  )
  await page.goto('/#/shelf')
  await page.reload()
  await expect(page.getByRole('heading', { name: '给下一本好书，留一个位置' })).toBeVisible()
  await page.goto('/#/notes')
  await expect(page.getByRole('heading', { name: '第一篇手记，从一个念头开始' })).toBeVisible()
  await page.goto('/#/missing')
  await expect(page.getByRole('link', { name: '返回首页' })).toBeVisible()
  await page.evaluate(() => localStorage.setItem('zhijian-library-v1', 'broken'))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('无法读取本地记录')
})
